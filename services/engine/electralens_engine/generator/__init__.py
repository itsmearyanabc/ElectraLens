"""Synthetic electoral-roll generator (B02).

Produces two roll versions of fictional electors in fictional places, one polling station per
part, and a ground-truth file of injected anomalies. Same seed, same bytes.
"""

import hashlib
import json
from dataclasses import asdict, dataclass
from pathlib import Path

from electralens_engine import __version__
from electralens_engine.csv_io import write_rows
from electralens_engine.generator.anomalies import Injector
from electralens_engine.generator.booths import build_booths
from electralens_engine.generator.evolve import evolve
from electralens_engine.generator.model import BOOTH_COLUMNS, ROLL_COLUMNS, Elector, Rng
from electralens_engine.generator.population import (
    POLLING_STATION_CAP,
    REGIONS,
    Population,
    assign_serials,
    build_baseline,
    build_geography,
)

NOTICE = (
    "SYNTHETIC DATA. Every person, constituency, part and polling station in these files is "
    "fictional, generated by ElectraLens for testing and demonstration. State and district names "
    "are real places used only for realism; nothing here describes their actual electoral rolls."
)
VERSIONS = (("v1", "2026-01-01"), ("v2", "2027-01-01"))
MIN_TOTAL_PARTS = 30


@dataclass(frozen=True)
class GeneratorConfig:
    seed: int = 42
    state: str = "HR"
    acs: int = 3
    parts_min: int = 36
    parts_max: int = 48
    electors_min: int = 600
    electors_max: int = 1200

    def validate(self) -> None:
        if self.state not in REGIONS:
            raise ValueError(f"state must be one of {', '.join(REGIONS)}")
        if not 1 <= self.parts_min <= self.parts_max:
            raise ValueError("need 1 <= parts_min <= parts_max")
        if self.acs * self.parts_min < MIN_TOTAL_PARTS:
            raise ValueError(f"need at least {MIN_TOTAL_PARTS} parts (acs x parts_min)")
        if not 100 <= self.electors_min <= self.electors_max <= POLLING_STATION_CAP:
            raise ValueError(f"need 100 <= electors_min <= electors_max <= {POLLING_STATION_CAP}")


def _sorted_rows(electors: list[Elector], qualifying_date: str) -> list[dict]:
    ordered = sorted(electors, key=lambda e: (e.ac_code, e.part_no, e.serial_no))
    return [e.row(qualifying_date) for e in ordered]


def _write_json(path: Path, data: object) -> None:
    path.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n"
    )


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def generate(config: GeneratorConfig, out_dir: Path) -> list[str]:
    config.validate()
    rng = Rng(config.seed)
    geo = build_geography(rng, config.acs, config.parts_min, config.parts_max, config.state)
    pop = Population(rng, geo)
    injector = Injector(rng, pop, geo)

    v1 = build_baseline(rng, pop, geo, config.electors_min, config.electors_max)
    injector.inject_baseline(v1)
    assign_serials(v1)
    v2 = evolve(rng, pop, v1)
    injector.inject_revision(v1, v2)
    assign_serials(v2)
    booths = build_booths(rng, geo)

    out_dir.mkdir(parents=True, exist_ok=True)
    rolls = {"v1": v1, "v2": v2}
    versions = []
    for label, qualifying_date in VERSIONS:
        rows = _sorted_rows(rolls[label], qualifying_date)
        write_rows(out_dir / f"roll_{label}.csv", ROLL_COLUMNS, rows)
        deleted = sum(r["status"] == "deleted" for r in rows)
        versions.append(
            {
                "label": label,
                "file": f"roll_{label}.csv",
                "schema": "electoral_roll_v1",
                "qualifying_date": qualifying_date,
                "rows": len(rows),
                "active": len(rows) - deleted,
                "deleted": deleted,
            }
        )
    write_rows(out_dir / "booths.csv", BOOTH_COLUMNS, booths)
    _write_json(
        out_dir / "jurisdictions.json",
        {"notice": NOTICE, "is_synthetic": True, "areas": [a.as_json() for a in geo.areas()]},
    )
    truth = injector.ground_truth()
    _write_json(
        out_dir / "ground_truth.json",
        {"notice": NOTICE, "seed": config.seed, "entries": truth},
    )
    files = ["roll_v1.csv", "roll_v2.csv", "booths.csv", "jurisdictions.json", "ground_truth.json"]
    _write_json(
        out_dir / "generation.json",
        {
            "notice": NOTICE,
            "is_synthetic": True,
            "generator": f"electralens-engine {__version__}",
            "config": asdict(config),
            "versions": versions,
            "booths": {"file": "booths.csv", "schema": "polling_stations_v1", "rows": len(booths)},
            "sha256": {name: _sha256(out_dir / name) for name in files},
        },
    )
    return [
        f"wrote {out_dir}",
        *(
            f"  {v['file']}: {v['rows']} rows ({v['active']} active, {v['deleted']} deleted)"
            for v in versions
        ),
        f"  booths.csv: {len(booths)} polling stations",
        f"  ground_truth.json: {len(truth)} entries",
    ]
