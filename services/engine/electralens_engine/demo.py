"""Demo content: what a real publication leaves behind, built from a synthetic dataset.

Takes the output of `el generate` and `el run` and produces the rows the full pipeline would
write (dataset versions, the run, reviewed findings, suppressed aggregates, one published
publication with its manifest and two approvals, published booths, moderated claims) plus the
public artifacts (manifest, report, aggregates) as the exact bytes that are hashed.

Everything is synthetic and marked so. The three demo staff accounts exist only so approvals and
reviews have authors: they have no password and cannot sign in. Local development only.
"""

import csv
import hashlib
import json
import secrets
import uuid
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

from electralens_engine.publish import (
    aggregates_document,
    manifest_document,
    published_aggregates,
    report_document,
)
from electralens_engine.publish import artifacts as publication_artifacts
from electralens_engine.seed import (
    DEMO_SOURCE_NAME,
    NAMESPACE,
    _insert,
    _literal,
    area_id,
    source_id,
)

SERIES = "DEMO-HR"
CLAIM_METHOD = "claims-2026.1"
CROCKFORD = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"

ACTORS = {
    "analyst": "00000000-0000-4000-8000-00000000d001",
    "reviewer": "00000000-0000-4000-8000-00000000d002",
    "publisher": "00000000-0000-4000-8000-00000000d003",
}


def _id(name: str) -> str:
    return str(uuid.uuid5(NAMESPACE, name))


def _iso(moment: datetime) -> str:
    return moment.astimezone(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def booth_code() -> str:
    """10 Crockford base32 characters (50 bits) from a cryptographic source, as in B13.02."""
    return "".join(secrets.choice(CROCKFORD) for _ in range(10))


@dataclass(frozen=True)
class Review:
    decision: str
    reason: str | None


def review_for(finding: dict[str, Any], seen: dict[str, int]) -> Review:
    """Demo review decisions: mostly accepted, with one downgrade and one rejection to show both."""
    rule = finding["rule"]["id"]
    seen[rule] = seen.get(rule, 0) + 1
    if rule == "R12" and seen[rule] == 1:
        return Review(
            "downgraded",
            "Small part; the shift is partly explained by a recorded part reorganisation.",
        )
    if rule == "R02" and seen[rule] == 2:
        return Review(
            "rejected",
            "The pairs are different family members with similar names at different house numbers.",
        )
    return Review("accepted", None)


@dataclass
class DemoContent:
    sql: str
    artifacts: dict[str, bytes]
    publication_id: str
    manifest_hash: str


def build_demo(demo_dir: Path, engine_rev: str, now: datetime | None = None) -> DemoContent:
    now = now or datetime.now(UTC).replace(microsecond=0)
    generation = json.loads((demo_dir / "generation.json").read_text(encoding="utf-8"))
    run = json.loads((demo_dir / "run" / "run.json").read_text(encoding="utf-8"))
    findings = json.loads((demo_dir / "run" / "findings.json").read_text(encoding="utf-8"))
    aggregates = json.loads((demo_dir / "run" / "aggregates.json").read_text(encoding="utf-8"))

    run_id = run["run_id"]
    finished = now - timedelta(days=2)
    reviewed = now - timedelta(days=1, hours=6)
    approved = now - timedelta(hours=20)
    published_at = now - timedelta(hours=18)
    versions = {v["label"]: v for v in generation["versions"]}
    sql: list[str] = [
        "-- Generated by `uv run el demo-sql`. Local development and the demo only.",
        "-- Synthetic content: fictional people, constituencies, parts and polling stations.",
        "begin;",
        "",
    ]

    # Authors for reviews and approvals. No password: these accounts cannot sign in.
    users = ",\n".join(
        f"  ('{uid}', '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated', "
        f"'{role}@demo.electralens.invalid', '', now(), "
        '\'{"provider": "email", "providers": ["email"]}\'::jsonb, '
        f'\'{{"display_name": "Demo {role}"}}\'::jsonb, now(), now())'
        for role, uid in ACTORS.items()
    )
    sql += [
        "insert into auth.users (id, instance_id, aud, role, email, encrypted_password, "
        "email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at) values",
        users + "\non conflict (id) do nothing;",
        # Supabase Auth reads these token columns as strings and fails to list users on NULL.
        "update auth.users set confirmation_token = '', recovery_token = '', "
        "email_change_token_new = '', email_change = '', email_change_token_current = '', "
        "phone_change = '', phone_change_token = '', reauthentication_token = '' "
        "where email like '%@demo.electralens.invalid';",
        "",
        # A constant id, quoted by _literal: offline generation, never user input.
        "update public.data_sources set is_public = true where id = "  # noqa: S608
        + _literal(source_id(DEMO_SOURCE_NAME))
        + ";",
        "",
    ]

    # Dataset versions: the two rolls the run compared.
    version_rows = []
    for role, label in (("baseline", "v1"), ("target", "v2")):
        info = run[role]
        csv_path = demo_dir / versions[label]["file"]
        version_rows.append(
            [
                _literal(info["version_id"]),
                _literal(source_id(DEMO_SOURCE_NAME)),
                _literal("electoral_roll"),
                _literal(f"Haryana DEMO roll {label} (qualifying date {info['qualifying_date']})"),
                _literal(info["qualifying_date"]),
                _literal("final" if role == "baseline" else "draft"),
                _literal("electoral_roll_v1"),
                _literal(area_id(SERIES)),
                _literal("approved"),
                _literal(hashlib.sha256(csv_path.read_bytes()).hexdigest()),
                _literal(info["root"]),
                str(info["row_count"]),
                "true",
                "true",
                _literal(ACTORS["analyst"]),
                _literal(_iso(finished - timedelta(days=1))),
            ]
        )
    sql += [
        _insert(
            "dataset_versions",
            [
                "id",
                "source_id",
                "kind",
                "label",
                "qualifying_date",
                "roll_stage",
                "schema_version",
                "jurisdiction_id",
                "status",
                "original_sha256",
                "canonical_root",
                "row_count",
                "is_synthetic",
                "is_public",
                "approved_by",
                "approved_at",
            ],
            version_rows,
        ),
        "",
    ]

    # The audit run.
    sql += [
        _insert(
            "audit_runs",
            [
                "id",
                "baseline_version_id",
                "target_version_id",
                "methodology_version",
                "status",
                "engine_version",
                "params_hash",
                "input_roots",
                "output_hash",
                "tests_in_run",
                "created_by",
                "started_at",
                "finished_at",
            ],
            [
                [
                    _literal(run_id),
                    _literal(run["baseline"]["version_id"]),
                    _literal(run["target"]["version_id"]),
                    _literal(run["methodology"]),
                    _literal("ready_for_review"),
                    _literal(engine_rev),
                    _literal(run["params_hash"]),
                    _literal(
                        {"baseline": run["baseline"]["root"], "target": run["target"]["root"]}
                    ),
                    _literal(run["output_hash"]),
                    _literal(run["tests_in_run"]),
                    _literal(ACTORS["analyst"]),
                    _literal(_iso(finished - timedelta(minutes=4))),
                    _literal(_iso(finished)),
                ]
            ],
        ),
        "",
    ]

    # Findings, each reviewed by someone other than the run's creator.
    seen: dict[str, int] = {}
    finding_rows, review_rows, reviewed_findings = [], [], []
    review_counts = {"accepted": 0, "downgraded": 0, "rejected": 0}
    for finding in findings:
        review = review_for(finding, seen)
        review_counts[review.decision] += 1
        doc = {**finding, "review": {"status": review.decision, "reviewed_at": _iso(reviewed)}}
        published = review.decision != "rejected" and doc["signal_strength"] != "weak"
        finding_id = _id(f"finding:{run_id}:{doc['finding_id']}")
        finding_rows.append(
            [
                _literal(finding_id),
                _literal(run_id),
                _literal(doc["finding_id"]),
                _literal(doc["rule"]["id"]),
                _literal(doc["rule"]["version"]),
                _literal(area_id(doc["area"]["code"])),
                _literal(doc["signal_strength"]),
                _literal(doc),
                _literal(review.decision),
                "true" if published else "false",
            ]
        )
        review_rows.append(
            [
                _literal(_id(f"review:{finding_id}")),
                _literal(finding_id),
                _literal(ACTORS["reviewer"]),
                _literal(review.decision),
                _literal(review.reason),
                _literal(_iso(reviewed)),
            ]
        )
        reviewed_findings.append(doc)
    sql += [
        _insert(
            "anomaly_findings",
            [
                "id",
                "run_id",
                "finding_code",
                "rule_id",
                "rule_version",
                "jurisdiction_id",
                "signal_strength",
                "finding",
                "review_status",
                "published",
            ],
            finding_rows,
        ),
        "",
        _insert(
            "finding_reviews",
            ["id", "finding_id", "reviewer_id", "decision", "reason", "created_at"],
            review_rows,
        ),
        "",
    ]

    # Published aggregates, report and manifest: the same code the worker uses.
    published_rows = published_aggregates(aggregates)
    aggregates_doc = aggregates_document(SERIES, 1, run_id, published_rows)
    benchmark = None
    benchmark_path = demo_dir / "run" / "benchmark.json"
    if benchmark_path.exists():
        # Detection quality against the generator's ground truth (synthetic data only).
        raw = json.loads(benchmark_path.read_text(encoding="utf-8"))
        fields = ("precision", "recall", "true_positives", "false_positives", "false_negatives")
        benchmark = {
            "overall": {k: raw["overall"][k] for k in fields},
            "per_rule": {
                rule: {k: values[k] for k in fields if k in values}
                for rule, values in raw["per_rule"].items()
            },
        }
    report_doc = report_document(
        series=SERIES,
        sequence=1,
        is_synthetic=True,
        notice=generation["notice"],
        run={
            "id": run_id,
            "methodology": run["methodology"],
            "params_hash": run["params_hash"],
            "engine": engine_rev,
            "output_hash": run["output_hash"],
            "parts": run["parts"],
            "every_part_tested": run["every_part_tested"],
            "tests_in_run": run["tests_in_run"],
        },
        datasets={"baseline": run["baseline"], "target": run["target"]},
        findings=reviewed_findings,
        review_counts=review_counts,
        benchmark=benchmark,
    )
    manifest = manifest_document(
        series=SERIES,
        sequence=1,
        previous_manifest_hash=None,
        is_synthetic=True,
        datasets=[
            {
                "role": role,
                "version_id": run[role]["version_id"],
                "root": run[role]["root"],
                "row_count": run[role]["row_count"],
                "schema": "electoral_roll_v1",
                "canon": "elcanon-1",
            }
            for role in ("baseline", "target")
        ],
        audit_run={
            "id": run_id,
            "engine": engine_rev,
            "image": None,
            "methodology": run["methodology"],
            "params_hash": run["params_hash"],
        },
        report=report_doc,
        aggregates=aggregates_doc,
        published_at=_iso(published_at),
    )
    m_hash, artifacts = publication_artifacts(SERIES, 1, manifest, report_doc, aggregates_doc)
    publication_id = _id(f"publication:{SERIES}:1")
    folder = f"{SERIES}/1"
    sql += [
        _insert(
            "publications",
            [
                "id",
                "series_id",
                "sequence",
                "run_id",
                "status",
                "manifest",
                "manifest_hash",
                "report_path",
                "report_hash",
                "aggregates_path",
                "aggregates_hash",
                "is_synthetic",
                "created_by",
                "submitted_at",
                "approved_at",
                "published_at",
            ],
            [
                [
                    _literal(publication_id),
                    _literal(SERIES),
                    "1",
                    _literal(run_id),
                    # Approved, not yet published: `pnpm demo:reset` anchors it through the anchor
                    # service, which publishes it with a real transaction (or falls back, offline).
                    _literal("approved"),
                    _literal(manifest),
                    _literal(m_hash),
                    _literal(f"{folder}/report.json"),
                    _literal(manifest["report_hash"]),
                    _literal(f"{folder}/aggregates.json"),
                    _literal(manifest["aggregates_hash"]),
                    "true",
                    _literal(ACTORS["publisher"]),
                    _literal(_iso(reviewed)),
                    _literal(_iso(approved)),
                    "null",
                ]
            ],
        ),
        "",
        _insert(
            "publication_approvals",
            ["publication_id", "approver_id", "step", "manifest_hash", "decision", "created_at"],
            [
                [
                    _literal(publication_id),
                    _literal(ACTORS["reviewer"]),
                    _literal("review"),
                    _literal(m_hash),
                    _literal("approve"),
                    _literal(_iso(approved - timedelta(hours=2))),
                ],
                [
                    _literal(publication_id),
                    _literal(ACTORS["publisher"]),
                    _literal("publish"),
                    _literal(m_hash),
                    _literal("approve"),
                    _literal(_iso(approved)),
                ],
            ],
        ),
        "",
    ]

    aggregate_sql_rows = [
        [
            _literal(run_id),
            _literal(publication_id),
            _literal(area_id(row["area_code"])),
            _literal(row["metric"]),
            _literal(row["dims"]),
            "null" if row["value"] is None else str(row["value"]),
            "true" if row["suppressed"] else "false",
            "true",
        ]
        for row in published_rows
    ]
    sql += [
        _insert(
            "aggregate_metrics",
            [
                "run_id",
                "publication_id",
                "jurisdiction_id",
                "metric",
                "dims",
                "value",
                "suppressed",
                "published",
            ],
            aggregate_sql_rows,
        ),
        "",
    ]

    sql += [_booths_sql(demo_dir / "booths.csv", now), ""]
    sql += [_claims_sql(published_rows, publication_id, now), ""]
    sql += ["commit;", ""]

    if hashlib.sha256(artifacts[f"{folder}/manifest.json"]).hexdigest() != m_hash:
        raise RuntimeError("manifest bytes do not hash to the manifest hash")
    return DemoContent("\n".join(sql), artifacts, publication_id, m_hash)


def _booths_sql(path: Path, now: datetime) -> str:
    rows = []
    with path.open(encoding="utf-8", newline="") as handle:
        for booth in csv.DictReader(handle):
            access = {
                key.split(".", 1)[1]: booth[key] == "true"
                for key in booth
                if key.startswith("accessibility.")
            }
            rows.append(
                [
                    _literal(booth_code()),
                    _literal(booth["station_code"]),
                    _literal(area_id(booth["ac_code"])),
                    "'{" + ",".join(booth["parts_served"].split(";")) + "}'::integer[]",
                    _literal({"en": booth["name.en"], "hi": booth["name.hi"]}),
                    _literal({"en": booth["address.en"], "hi": booth["address.hi"]}),
                    _literal(access),
                    _literal(booth["source_url"] or None),
                    _literal(_iso(now - timedelta(days=3))),
                    "true",
                    "true",
                ]
            )
    return _insert(
        "polling_stations",
        [
            "public_code",
            "station_code",
            "ac_id",
            "parts_served",
            "name",
            "address",
            "accessibility",
            "source_url",
            "verified_at",
            "is_synthetic",
            "published",
        ],
        rows,
    )


def _claims_sql(rows: list[dict[str, Any]], publication_id: str, now: datetime) -> str:
    """Three moderated claims, one per verdict the demo needs, checked against the aggregates."""

    def value(area: str, metric: str) -> int:
        for row in rows:
            if row["area_code"] == area and row["metric"] == metric and not row["dims"]:
                return int(row["value"])
        raise KeyError((area, metric))

    deletions = value("DEMO-HR-AC901", "deletions")
    additions = value("DEMO-HR-AC903", "additions")
    claims = [
        {
            "text": (
                f"More than {deletions * 2:,} names were deleted in Gurugram DEMO-1 this revision."
            ),
            "structured": {
                "area_code": "DEMO-HR-AC901",
                "metric": "deletions",
                "period": "2027",
                "comparator": "gt",
                "value": deletions * 2,
                "unit": "count",
                "claim_type": "quantity",
            },
            "verdict": "contradicted",
            "published_value": deletions,
            "explanation": {
                "en": f"The published roll comparison records {deletions:,} deletions in Gurugram "
                f"DEMO-1, fewer than the {deletions * 2:,} claimed.",
                "hi": f"प्रकाशित सूची-तुलना में गुरुग्राम डेमो-1 में {deletions:,} नाम हटाए गए दर्ज हैं, "
                f"जो दावा किए गए {deletions * 2:,} से कम हैं।",
            },
        },
        {
            "text": f"About {round(additions, -2):,} names were added in Faridabad DEMO-1.",
            "structured": {
                "area_code": "DEMO-HR-AC903",
                "metric": "additions",
                "period": "2027",
                "comparator": "approx",
                "value": round(additions, -2),
                "unit": "count",
                "claim_type": "quantity",
            },
            "verdict": "consistent",
            "published_value": additions,
            "explanation": {
                "en": f"The published comparison records {additions:,} additions in Faridabad "
                "DEMO-1, within the tolerance of the claimed figure.",
                "hi": f"प्रकाशित तुलना में फ़रीदाबाद डेमो-1 में {additions:,} नाम जोड़े गए दर्ज हैं, "
                "जो दावा की गई संख्या की सहनशीलता सीमा के भीतर है।",
            },
        },
        {
            "text": "The deletions in Part 1 of Gurugram DEMO-1 were made to remove one community.",
            "structured": {
                "area_code": "DEMO-HR-AC901-P001",
                "metric": "deletions",
                "period": "2027",
                "comparator": "cause",
                "value": None,
                "unit": "count",
                "claim_type": "cause_or_intent",
            },
            "verdict": "cannot_establish",
            "published_value": None,
            "explanation": {
                "en": "Published roll data records how many names changed, not why or with what "
                "intent. A claim about cause or intent cannot be established from it.",
                "hi": "प्रकाशित सूची डेटा में यह दर्ज होता है कि कितने नाम बदले, यह नहीं कि क्यों या "
                "किस इरादे से। कारण या इरादे के दावे की पुष्टि इससे नहीं हो सकती।",
            },
        },
    ]
    claim_rows, assessment_rows = [], []
    for index, claim in enumerate(claims, start=1):
        claim_id = _id(f"claim:demo:{index}")
        moderated = _iso(now - timedelta(hours=10 - index))
        claim_rows.append(
            [
                _literal(claim_id),
                _literal(claim["text"]),
                _literal(claim["structured"]),
                _literal("en"),
                _literal("published"),
                _literal(ACTORS["reviewer"]),
                _literal(moderated),
            ]
        )
        assessment_rows.append(
            [
                _literal(_id(f"assessment:demo:{index}")),
                _literal(claim_id),
                _literal(claim["verdict"]),
                _literal(
                    {
                        "area_code": claim["structured"]["area_code"],
                        "metric": claim["structured"]["metric"],
                        "published_value": claim["published_value"],
                        "tolerance": {"relative": "0.01", "absolute": 10},
                    }
                ),
                _literal(publication_id),
                _literal(CLAIM_METHOD),
                _literal(claim["explanation"]),
            ]
        )
    return "\n".join(
        [
            _insert(
                "claim_submissions",
                ["id", "text", "structured", "language", "status", "moderated_by", "moderated_at"],
                claim_rows,
            ),
            "",
            _insert(
                "claim_assessments",
                [
                    "id",
                    "claim_id",
                    "verdict",
                    "evidence",
                    "publication_id",
                    "method_version",
                    "explanation",
                ],
                assessment_rows,
            ),
        ]
    )


def write_demo(demo_dir: Path, out_dir: Path, engine_rev: str) -> DemoContent:
    content = build_demo(demo_dir, engine_rev)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "demo.sql").write_text(content.sql, encoding="utf-8", newline="\n")
    for name, data in content.artifacts.items():
        target = out_dir / "artifacts" / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    return content
