"""Generates supabase/seed.sql: demo areas, the synthetic data source and methodology 2026.1.

IDs are UUIDv5 from stable names, so the seed, the engine and the worker agree on them
without a lookup. Seeds hold no users and no passwords.
"""

import json
import uuid
from pathlib import Path
from typing import Any

from electralens_engine.methodology import load_methodology, params_hash

NAMESPACE = uuid.uuid5(uuid.NAMESPACE_URL, "urn:electralens")
LEVEL_ORDER = {"state": 0, "district": 1, "ac": 2, "part": 3}
DEMO_SOURCE_NAME = "ElectraLens synthetic demo data"


def area_id(code: str) -> str:
    return str(uuid.uuid5(NAMESPACE, f"area:{code}"))


def source_id(name: str) -> str:
    return str(uuid.uuid5(NAMESPACE, f"source:{name}"))


def _literal(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, dict | list):
        return (
            "'"
            + json.dumps(value, ensure_ascii=False, sort_keys=True).replace("'", "''")
            + "'::jsonb"
        )
    return "'" + str(value).replace("'", "''") + "'"


def seed_sql(areas: list[dict[str, Any]], methodology_version: str = "2026.1") -> str:
    lines = [
        "-- Generated by `uv run el seed-sql`. Do not edit by hand.",
        "-- Local development only: demo areas (real state and district names, fictional",
        "-- constituencies and parts), the synthetic data source and the published methodology.",
        "",
    ]
    ordered = sorted(areas, key=lambda a: (LEVEL_ORDER[a["level"]], a["code"]))
    area_rows = [
        [
            _literal(area_id(a["code"])),
            _literal(a["code"]),
            _literal(a["level"]),
            _literal(area_id(a["parent"]) if a["parent"] else None),
            _literal(a["name"]),
            _literal(a.get("introduced_in")),
            "true",
        ]
        for a in ordered
    ]
    columns = ["id", "code", "level", "parent_id", "name", "introduced_in", "is_synthetic"]
    lines += [_insert("jurisdictions", columns, area_rows), ""]

    source_row = [
        _literal(source_id(DEMO_SOURCE_NAME)),
        _literal(DEMO_SOURCE_NAME),
        _literal("ElectraLens"),
        "null",
        _literal("synthetic"),
        _literal("Generated by el generate. Fictional people and places."),
        "true",
    ]
    columns = ["id", "name", "publisher", "url", "permission_basis", "licence_note", "is_synthetic"]
    lines += [_insert("data_sources", columns, [source_row]), ""]

    params = load_methodology(methodology_version)
    methodology_row = [
        _literal(methodology_version),
        _literal(params),
        _literal(params_hash(methodology_version)),
        _literal("published"),
        _literal(params.get("description")),
        "now()",
        "now()",
    ]
    columns = ["version", "params", "params_hash", "status", "notes", "frozen_at", "published_at"]
    lines.append(_insert("methodology_versions", columns, [methodology_row]))
    return "\n".join(lines) + "\n"


def _insert(table: str, columns: list[str], rows: list[list[str]]) -> str:
    """An INSERT from already-quoted literals. Offline seed generation only, never user input."""
    values = ",\n".join("  (" + ", ".join(row) + ")" for row in rows)
    return f"insert into public.{table} ({', '.join(columns)}) values\n{values};"


def write_seed(areas_path: Path, out: Path) -> Path:
    areas = json.loads(areas_path.read_text(encoding="utf-8"))["areas"]
    out.write_text(seed_sql(areas), encoding="utf-8", newline="\n")
    return out
