// Makes the ten synthetic demo voter cards: the SQL that stores them (PINs only as bcrypt hashes,
// computed by the database) and a printable card sheet with each card's QR code and PIN.
// Both go to data/demo/, which is gitignored: the sheet shows the PINs.
//
//   node apps/web/scripts/demo-voter-cards.mjs <booths.json> [origin] [outDir]
//
// booths.json: [{ "public_code": "...", "part": 12, "name": "..." }, ...] (ten published booths).
import { randomInt } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import QRCode from 'qrcode';

const [boothFile, origin = 'https://electralens.armedias.com', outDir = 'data/demo'] =
  process.argv.slice(2);
if (!boothFile) throw new Error('usage: demo-voter-cards.mjs <booths.json> [origin] [outDir]');
const booths = JSON.parse(readFileSync(boothFile, 'utf8'));
if (booths.length < 10) throw new Error('need ten booths');

const CROCKFORD = '0123456789ABCDEFGHJKMNPQRSTVWXYZ';
const code = () => Array.from({ length: 10 }, () => CROCKFORD[randomInt(32)]).join('');
const digits = (n) => Array.from({ length: n }, () => randomInt(10)).join('');

// Fictional people. Any resemblance to a real person is coincidental.
const PEOPLE = [
  ['Aarav Malhotra', 1988, 'M'],
  ['Priya Sharma', 1995, 'F'],
  ['Rohan Verma', 2004, 'M'],
  ['Kavya Iyer', 1979, 'F'],
  ['Imran Qureshi', 1983, 'M'],
  ['Simran Kaur', 2001, 'F'],
  ['Vikram Rathore', 1965, 'M'],
  ['Ananya Das', 1999, 'F'],
  ['Mohit Yadav', 1991, 'M'],
  ['Nisha Gupta', 1972, 'F'],
];

// Synthetic elections, named as such: ElectraLens holds no real voting records.
const ELECTIONS = [
  { id: 'demo-ls-2014', name: 'General election 2014 (demo)', year: 2014 },
  { id: 'demo-vs-2014', name: 'State assembly election 2014 (demo)', year: 2014 },
  { id: 'demo-ls-2019', name: 'General election 2019 (demo)', year: 2019 },
  { id: 'demo-vs-2019', name: 'State assembly election 2019 (demo)', year: 2019 },
  { id: 'demo-ls-2024', name: 'General election 2024 (demo)', year: 2024 },
  { id: 'demo-vs-2024', name: 'State assembly election 2024 (demo)', year: 2024 },
];
// How often each demo citizen turns out, so the sheet shows a range from never missing to often.
const TURNOUT = [1, 0.85, 0.5, 0.9, 0.7, 0.6, 1, 0.35, 0.8, 0.95];

const cards = PEOPLE.map(([name, birthYear, gender], index) => {
  const booth = booths[index];
  const eligible = ELECTIONS.filter((e) => e.year - birthYear >= 18);
  const participation = eligible.map((e) => ({
    election: e.name,
    year: e.year,
    voted: index === 0 || index === 6 ? true : Math.random() < TURNOUT[index],
  }));
  return {
    cardCode: code(),
    cardNumber: `ELD-${digits(4)}-${digits(4)}`,
    pin: digits(4),
    name,
    birthYear,
    gender,
    booth,
    part: booth.part,
    serial: 1 + randomInt(900),
    participation,
  };
});

const sqlText = (value) => `'${String(value).replace(/'/g, "''")}'`;
const sql = [
  '-- Generated by apps/web/scripts/demo-voter-cards.mjs. Synthetic demo voter cards.',
  'begin;',
  'delete from public.demo_voter_cards;',
  ...cards.map(
    (c) =>
      `insert into public.demo_voter_cards (card_code, card_number, holder_name, birth_year, gender, polling_station_id, part_number, serial_number, pin_hash, participation)
select ${sqlText(c.cardCode)}, ${sqlText(c.cardNumber)}, ${sqlText(c.name)}, ${c.birthYear}, ${sqlText(c.gender)}, id, ${c.part}, ${c.serial}, extensions.crypt(${sqlText(c.pin)}, extensions.gen_salt('bf')), ${sqlText(JSON.stringify(c.participation))}::jsonb
from public.polling_stations where public_code = ${sqlText(c.booth.public_code)} and published;`,
  ),
  'commit;',
  '',
].join('\n');

const escape = (s) =>
  String(s).replace(
    /[&<>"]/g,
    (ch) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[ch],
  );
const qr = await Promise.all(
  cards.map((c) =>
    QRCode.toString(`${origin}/v/${c.cardCode}`, {
      type: 'svg',
      errorCorrectionLevel: 'M',
      margin: 1,
      color: { dark: '#172033', light: '#ffffff' },
    }),
  ),
);
const html = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>ElectraLens demo voter cards</title>
<meta name="viewport" content="width=device-width, initial-scale=1">
<style>
  body { font-family: system-ui, sans-serif; margin: 24px; color: #172033; }
  h1 { font-size: 20px; margin: 0 0 4px; } p.note { color: #475467; margin: 0 0 20px; font-size: 13px; }
  .grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(330px, 1fr)); gap: 16px; }
  .card { border: 1px solid #d0d5dd; border-radius: 16px; overflow: hidden; break-inside: avoid; }
  .top { background: linear-gradient(90deg, #f07824 0 33%, #ffffff 33% 66%, #14663f 66%); height: 6px; }
  .body { display: flex; gap: 14px; padding: 14px; align-items: center; }
  .qr { width: 118px; flex: none; } .qr svg { width: 100%; height: auto; }
  .k { font-size: 10px; letter-spacing: .12em; text-transform: uppercase; color: #475467; }
  .v { font-weight: 700; margin-bottom: 6px; } .num { font-family: ui-monospace, monospace; }
  .demo { background: #fff4ec; color: #9a440d; font-size: 11px; padding: 6px 14px; }
  .pin { font-family: ui-monospace, monospace; font-size: 15px; font-weight: 700; color: #1d4fb8; }
  @media print { body { margin: 8mm; } p.note { display: none; } }
</style></head><body>
<h1>ElectraLens demo voter cards</h1>
<p class="note">Ten fictional citizens. Scan a QR code to see the polling booth; enter the PIN on the page to see the synthetic participation history. Keep this sheet private: it shows the PINs.</p>
<div class="grid">
${cards
  .map(
    (c, i) => `<div class="card"><div class="top"></div><div class="body">
<div class="qr">${qr[i]}</div>
<div>
<div class="k">Demo voter card</div><div class="v num">${escape(c.cardNumber)}</div>
<div class="k">Name</div><div class="v">${escape(c.name)}</div>
<div class="k">Born · Part · Serial</div><div class="v">${c.birthYear} · ${c.part} · ${c.serial}</div>
<div class="k">PIN</div><div class="pin">${c.pin}</div>
</div></div><div class="demo">Synthetic demo card — not a real EPIC. ElectraLens is not affiliated with the ECI.</div></div>`,
  )
  .join('\n')}
</div></body></html>
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(path.join(outDir, 'voter-cards.sql'), sql);
writeFileSync(path.join(outDir, 'voter-cards.html'), html);
console.log(
  `wrote ${path.join(outDir, 'voter-cards.sql')} and voter-cards.html (${cards.length} cards)`,
);
for (const c of cards) {
  const missed = c.participation.filter((p) => !p.voted).length;
  console.log(
    `${c.cardNumber}  ${c.name.padEnd(16)} /v/${c.cardCode}  missed ${missed}/${c.participation.length}`,
  );
}
